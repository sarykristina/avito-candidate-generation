"""
Вспомогательные функции предобработки текста.

Корпус — это русскоязычный, неформальный текст объявлений услуг Avito
(заголовки, описания, значения фильтров). Мы намеренно делаем
предобработку максимально простой и полностью локальной (без скачивания
чего-либо, без внешних морфологических моделей — это одно из требований
задания: решение должно воспроизводиться локально без обращений к
внешним API):

    - приведение к нижнему регистру;
    - нормализация `ё` -> `е` (очень частый неформальный вариант написания,
      без неё одно и то же слово с ё/е считалось бы разными токенами);
    - небольшой, вручную составленный список русских стоп-слов
      (служебные части речи почти не несут сигнала для поиска по
      коротким запросам и только добавляют шум / увеличивают длину
      документа, что портит нормировку BM25 по длине).

Мы сознательно НЕ делаем стемминг/лемматизацию. Объявления услуг на
Avito полны имён, брендов, профессионального жаргона и редких составных
слов, для которых обобщённый стеммер с большей вероятностью склеит
разные по смыслу слова, чем поможет найти совпадение. Ручная проверка
показала, что обычные "сырые" токены уже дают достаточно сильное
лексическое пересечение для этой задачи (подробнее — в разделе
"Найденные ошибки" в README.md).
"""

import re

# Короткий список самых частых русских служебных слов (предлоги, союзы,
# местоимения и т.п.). Список НЕ исчерпывающий — это сделано намеренно:
# цель не в том, чтобы вычистить весь "мусор", а в том, чтобы эти слова
# не доминировали в частотах терминов. Любое другое очень частое слово
# и так получит низкий вес автоматически за счёт IDF внутри BM25.
RU_STOPWORDS = {
    "и", "в", "во", "не", "что", "он", "на", "я", "с", "со", "как", "а",
    "то", "все", "она", "так", "его", "но", "да", "ты", "к", "у", "же",
    "вы", "за", "бы", "по", "только", "ее", "мне", "было", "вот", "от",
    "меня", "еще", "нет", "о", "из", "ему", "теперь", "когда", "даже",
    "ну", "вдруг", "ли", "если", "уже", "или", "ни", "быть", "был", "него",
    "до", "вас", "нибудь", "опять", "уж", "вам", "сказал", "ведь", "там",
    "потом", "себя", "ничего", "ей", "может", "они", "тут", "где", "есть",
    "надо", "ней", "для", "мы", "тебя", "их", "чем", "была", "сам", "чтоб",
    "без", "будто", "чего", "раз", "тоже", "себе", "под", "будет", "ж",
    "тогда", "кто", "этот", "того", "потому", "этого", "какой", "совсем",
    "ним", "здесь", "этом", "один", "почти", "мой", "тем", "чтобы", "нее",
    "сейчас", "были", "куда", "зачем", "всех", "никогда", "можно", "при",
    "об", "какая", "который", "которая", "которые", "которых",
}

# Регулярка для извлечения "слов": латиница, кириллица и цифры подряд.
# re.IGNORECASE тут не обязателен (мы и так приводим текст к нижнему
# регистру до применения regex), но оставлен для устойчивости, если
# функцию когда-нибудь вызовут на несиженном тексте.
_TOKEN_RE = re.compile(r"[a-zа-я0-9]+", re.IGNORECASE)


def tokenize(text: str) -> list:
    """Привести текст к нижнему регистру и извлечь буквенно-цифровые
    токены (кириллица/латиница/цифры), отбросив стоп-слова и токены
    длиной в один символ (одиночные буквы/цифры почти никогда не несут
    смысла и только раздувают словарь)."""
    if not text:
        # Пустая строка / None (например, пустое item_infm_params_text
        # у части объявлений) -- просто нет токенов, это не ошибка.
        return []
    text = text.lower().replace("ё", "е")
    tokens = _TOKEN_RE.findall(text)
    return [t for t in tokens if len(t) > 1 and t not in RU_STOPWORDS]


def build_weighted_text(parts_with_weights) -> str:
    """Склеить несколько текстовых полей в одну bag-of-words строку,
    повторяя токены поля `weight` раз, чтобы они весили больше при
    обычном подсчёте частоты терминов (TF).

    Это дешёвая замена "честному" полевому BM25 (BM25F), где у каждого
    поля были бы свои IDF-статистики: вместо этого мы искусственно
    увеличиваем частоту термина в документе за счёт повторов, что даёт
    BM25 такой же эффект "поле важнее" без усложнения формулы. Конкретные
    веса для заголовка/параметров/описания подобраны офлайн-валидацией
    (см. src/data_prep.py и README.md).

    parts_with_weights: список пар (raw_text, weight:int)
    """
    tokens = []
    for raw_text, weight in parts_with_weights:
        toks = tokenize(raw_text)
        if weight > 1:
            toks = toks * weight
        tokens.extend(toks)
    return " ".join(tokens)
