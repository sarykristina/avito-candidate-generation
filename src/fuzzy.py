"""
Нечёткое сопоставление по символьным n-граммам -- дополняет точный по
словам BM25 (src/bm25.py). Обычная (по словам) токенизация ничего не
знает о словоформах, опечатках и разном разбиении составных слов:
запрос "маникюрный мастер" и объявление "мастер маникюра" делят только
слово "мастер" на уровне точных токенов, но на уровне символьных
3-5-грамм у них общий корень "маникюр" (и куча других 3-грамм), поэтому
символьное сходство ловит такую связь, а BM25 по словам -- нет.

Особенно важно это для объявлений, которые попали в кандидаты ТОЛЬКО
через расширение по локации (`build_location_index`, см. src/ranking.py)
с нулевым BM25-скором: для них символьное сходство -- единственный
источник хоть какого-то текстового сигнала вместо полного нуля.

Реализовано как TF-IDF по символьным n-граммам (не по словам) + обычная
косинусная близость через разреженное матричное произведение -- та же
идея, что и в src/bm25.py, просто с другим анализатором токенов
(`analyzer="char_wb"` в scikit-learn). `max_df=0.5` здесь даже важнее,
чем для BM25: символьных n-грамм на порядок меньше, чем слов, поэтому
без отсечки самые частые из них (например, "ени", "ани" -- обрывки
окончаний) встречаются почти в каждом документе и грозят той же
проблемой с плотностью и памятью, что описана в src/bm25.py.

Офлайн-валидация (scripts/run_validation.py) показала, что этот сигнал
полезен только с НЕБОЛЬШИМ весом: пик Recall@50 -- на alpha=0.1
(+0.0034 сверх пайплайна без нечёткого сопоставления), а при весе
заметно больше 0.3 recall начинает УХУДШАТЬСЯ (вплоть до -0.08 при
alpha=2.0) -- символьное сходство само по себе гораздо более шумный
сигнал, чем точное совпадение слов (случайные короткие слова нередко
разделяют много символьных n-грамм, не имея ничего общего по смыслу), и
при большом весе эта шумная близость начинает перевешивать надёжные
сигналы (точный BM25, локация, категория) вместо того, чтобы просто
"дозаполнять" их слепые зоны.
"""
from sklearn.feature_extraction.text import TfidfVectorizer


class FuzzyIndex:
    def __init__(self, ngram_range=(3, 5), min_df=3, max_df=0.5):
        self.vectorizer = TfidfVectorizer(
            analyzer="char_wb", ngram_range=ngram_range, min_df=min_df, max_df=max_df,
        )
        self.item_matrix = None  # (n_docs, n_char_ngrams), TF-IDF, L2-нормированная построчно

    def fit(self, doc_texts):
        """doc_texts -- сырой (не взвешенный повторением, в отличие от
        BM25) текст объявления, одна строка на объявление."""
        self.item_matrix = self.vectorizer.fit_transform(doc_texts)
        return self

    def transform_query(self, query_texts):
        return self.vectorizer.transform(query_texts)

    def score_chunked(self, query_texts, chunk_size: int = 200):
        """Считать косинусную близость запросов к корпусу порциями --
        та же причина, что и в BM25Index.score_chunked: даже после
        max_df-отсечки произведение может быть довольно плотным, чанки
        ограничивают пиковую память."""
        q_all = self.transform_query(query_texts)
        n = q_all.shape[0]
        for start in range(0, n, chunk_size):
            q_chunk = q_all[start:start + chunk_size]
            yield q_chunk @ self.item_matrix.T
